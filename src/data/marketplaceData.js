// AI pricing formula
export function calcSuggestedPrice(cert, sector, demandScore = 1.2) {
  const BASE = 1200;
  const certMult = cert === 'Gold Standard' ? 1.15 : cert === 'Verra VCS' ? 1.10 : 1.0;
  const sectorMult = {
    solar: 1.10, wind: 1.05, biogas: 1.18, blue: 1.25, forest: 1.08, transport: 1.15,
  }[sector] || 1.0;
  return Math.round(BASE * certMult * sectorMult * demandScore);
}
